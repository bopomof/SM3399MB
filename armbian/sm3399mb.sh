#!/usr/bin/env bash

# Keep the Armbian base configuration and add features used by RK3399 carrier
# boards. Board-specific GPIO routing stays in the vendor DTB or an overlay.
function custom_kernel_config__sm3399mb() {
	opts_y+=(
		WATCHDOG WATCHDOG_CORE WATCHDOG_SYSFS GPIO_WATCHDOG
		WATCHDOG_HANDLE_BOOT_ENABLED REGULATOR REGULATOR_FIXED_VOLTAGE
		I2C I2C_RK3X SERIAL_8250 SERIAL_8250_CONSOLE SERIAL_8250_DW
		SERIAL_OF_PLATFORM USB_NET_DRIVERS USB_USBNET
		STMMAC_ETH STMMAC_PLATFORM DWMAC_ROCKCHIP REALTEK_PHY
		MPTCP MPTCP_IPV6 INET_MPTCP_DIAG IP_ADVANCED_ROUTER
		IP_MULTIPLE_TABLES IP_ROUTE_MULTIPATH
	)
	opts_val[WATCHDOG_OPEN_TIMEOUT]="0"
	opts_val[SERIAL_8250_NR_UARTS]="10"
	opts_val[SERIAL_8250_RUNTIME_UARTS]="8"
	opts_val[DEFAULT_MPTCP_PM]='"mptcp_pm_kernel"'
	opts_m+=(
		USB_SERIAL USB_SERIAL_GENERIC USB_SERIAL_OPTION USB_SERIAL_WWAN
		USB_SERIAL_QUALCOMM USB_WDM USB_NET_CDCETHER USB_NET_CDC_EEM
		USB_NET_CDC_NCM USB_NET_HUAWEI_CDC_NCM USB_NET_CDC_MBIM
		USB_NET_QMI_WWAN USB_NET_RNDIS_HOST
		NETFILTER_XT_MATCH_MULTIPATH NETFILTER_XT_TARGET_MARK
		NETFILTER_XT_MATCH_MARK NETFILTER_XT_MATCH_CONNMARK
		NETFILTER_XT_TARGET_CONNMARK TCP_CONG_BBR NET_SCH_FQ
		NET_SCH_CAKE NET_SCH_CODEL NET_SCH_FQ_CODEL
		SND SND_SOC SND_SOC_ES8316 SND_SOC_ROCKCHIP_I2S
		SND_AUDIO_GRAPH_CARD
	)
}
